export type M04RepairHerb = {
  name?: unknown;
  dose?: unknown;
  prescriptionRole?: unknown;
  targetPathogenesis?: unknown;
  function?: unknown;
};

function recordValue(value: unknown): Record<string, unknown> | undefined {
  return value && typeof value === "object" && !Array.isArray(value)
    ? value as Record<string, unknown>
    : undefined;
}

function candidateRecord(value: unknown): Record<string, unknown> | undefined {
  if (typeof value === "string") {
    try {
      return candidateRecord(JSON.parse(value));
    } catch {
      return undefined;
    }
  }
  if (Array.isArray(value)) return value.length === 1 ? candidateRecord(value[0]) : undefined;
  return recordValue(value);
}

/**
 * Repair rounds use the compact `tcm-cdss-m04-proposal-v1` envelope while the first model round
 * uses the compiled `reasoning-v2` envelope. Repair diagnostics must understand both; otherwise a
 * second repair sees only a numeric herb index and loses the exact herb name/dose boundary.
 */
export function m04CandidateHerbsFromRepairPayload(value: unknown): M04RepairHerb[] {
  const root = recordValue(value);
  if (!root) return [];
  const proposalCandidate = candidateRecord(root.candidate);
  if (proposalCandidate && Array.isArray(proposalCandidate.herbs)) {
    return proposalCandidate.herbs.filter((herb): herb is M04RepairHerb => Boolean(recordValue(herb)));
  }
  const formula = recordValue(root.formula);
  const candidates = formula?.candidates;
  if (!Array.isArray(candidates) || candidates.length !== 1) return [];
  const compiledCandidate = candidateRecord(candidates[0]);
  return Array.isArray(compiledCandidate?.herbs)
    ? compiledCandidate.herbs.filter((herb): herb is M04RepairHerb => Boolean(recordValue(herb)))
    : [];
}

function candidateHerbContainer(value: unknown): M04RepairHerb[] | undefined {
  const root = recordValue(value);
  if (!root) return undefined;
  const proposalCandidate = candidateRecord(root.candidate);
  if (proposalCandidate && Array.isArray(proposalCandidate.herbs)) {
    return proposalCandidate.herbs as M04RepairHerb[];
  }
  return undefined;
}

/** One governed selector shared by repair prompting and post-model field stabilization. */
export function m04DoseRepairHerbIndex(rejectionReason: string): number | undefined {
  const match = rejectionReason.match(
    /^m04_candidate_0_herb_(\d+)_dose_(?:outside_conservative_range|sanity_ceiling)$/,
  );
  if (!match) return undefined;
  const index = Number(match[1]);
  return Number.isSafeInteger(index) && index >= 0 ? index : undefined;
}

/**
 * A dose-only repair must not redraw the rest of an already valid M04 proposal. Providers often
 * fix the named dose but also perturb another herb, role or regimen field, turning one bounded
 * defect into a repair cascade. Keep the rejected proposal byte-for-byte equivalent except for
 * the model-selected dose of the exact governed herb. The merged proposal still goes through the
 * complete deterministic contract, independent clinical review and external audit afterwards.
 *
 * Full reasoning-v2 payloads are deliberately not rewritten here: M04 repairs must return through
 * the minimal proposal compiler, so only proposal-v1 -> proposal-v1 repair rounds are eligible.
 */
export function stabilizeM04DoseOnlyRepair(
  rejectedJson: string,
  repairedJson: string,
  rejectionReason = "",
): string | undefined {
  const targetIndex = m04DoseRepairHerbIndex(rejectionReason);
  if (targetIndex == null) return undefined;
  try {
    const rejected = JSON.parse(rejectedJson) as Record<string, unknown>;
    const repaired = JSON.parse(repairedJson) as Record<string, unknown>;
    if (rejected.schemaVersion !== "tcm-cdss-m04-proposal-v1" || repaired.schemaVersion !== "tcm-cdss-m04-proposal-v1") {
      return undefined;
    }
    const rejectedHerbs = candidateHerbContainer(rejected);
    const repairedHerbs = candidateHerbContainer(repaired);
    const target = rejectedHerbs?.[targetIndex];
    const targetName = typeof target?.name === "string" ? target.name.trim() : "";
    if (!targetName || !rejectedHerbs || !repairedHerbs) return undefined;
    const repairedMatches = repairedHerbs.filter((herb) =>
      typeof herb?.name === "string" && herb.name.trim() === targetName,
    );
    const repairedDose = repairedMatches.length === 1 && typeof repairedMatches[0].dose === "string"
      ? repairedMatches[0].dose.trim()
      : "";
    if (!repairedDose) return undefined;
    target!.dose = repairedDose;
    return JSON.stringify(rejected);
  } catch {
    return undefined;
  }
}

const M04_KB_SHORTLIST_START = "【本例治法方向的知识库覆盖药味短名单";
const M04_KB_SHORTLIST_END = "【M04药味可引用病机节点】";

/** Preserve the governed, case-specific herb shortlist when the full M04 prompt is reduced to a
 * compact repair request. The returned block is generated by the server, never by patient text.
 *
 * 这个上限必须 ≥ diagnosis-prompts.ts 的 KB_COVERED_SHORTLIST_BUDGET（当前 4_000，另加 header
 * 与方向行前缀）。两处是各自独立的常量：只提高预算而不同步这里，修复轮注入的短名单会在药名
 * 中间被截断成 `黄芪[9-3` 这类残串，直接诱导模型输出非法药名。改一处必须同步另一处。 */
export function m04KnowledgeShortlistFromPrompt(prompt: string): string {
  const start = prompt.indexOf(M04_KB_SHORTLIST_START);
  if (start < 0) return "";
  const end = prompt.indexOf(M04_KB_SHORTLIST_END, start);
  if (end <= start) return "";
  return prompt.slice(start, end).trim().slice(0, 6_000);
}

